def same(a, b):
    if a == b:
        return True
    if isinstance(a, (list, tuple)) and isinstance(b, (list, tuple)):
        return len(a) == len(b) and all(same(v, w) for v, w in zip(a, b))
    if isinstance(a, (str, bool)) or isinstance(b, (str, bool)):
        return a == b
    if isinstance(a, s.logic.boolalg.Boolean) or isinstance(b, s.logic.boolalg.Boolean):
        return s.simplify_logic(s.Equivalent(a, b)) == s.true
    return s.simplify(s.sympify(a) - s.sympify(b)) == 0


